#!/usr/bin/env bash
# Docker entrypoint for El-equipo-AI.
# Sets up OpenCode with Superpowers hooks integration.

set -e

# ---- OpenCode + Superpowers hooks setup ----
if command -v opencode &>/dev/null && [ -d "/superpowers" ]; then
    # Ensure OpenCode config directory exists
    mkdir -p "${HOME}/.config/opencode"

    # Set up Superpowers as OpenCode hooks if not already configured.
    # OpenCode hooks auto-bootstrap Superpowers methodology on agent start.
    if [ ! -f "${HOME}/.config/opencode/config.toml" ]; then
        cat > "${HOME}/.config/opencode/config.toml" <<'EOF'
# OpenCode config — auto-generated by El-equipo-AI entrypoint
#
# PLACEHOLDER: Superpowers hooks integration.
#
# This config should define OpenCode hooks that load Superpowers methodology
# (brainstorm, TDD, code review, debugging skills) on agent startup.
#
# HOW TO ENABLE: Replace the [hooks.startup] section below with the actual
# OpenCode hooks syntax once the hooks API is stable. The hooks should source
# skill definitions from /superpowers/ so agents follow the methodology.
#
# WHEN: After verifying OpenCode's hooks schema (check `opencode --help` or
# https://opencode.ai/docs). The entrypoint regenerates this file only if it
# doesn't already exist, so manual edits are preserved across container restarts.

[hooks.startup]
command = "echo 'Superpowers methodology available at /superpowers'"
EOF
    fi

    export SUPERPOWERS_DIR="/superpowers"
fi

# Hand off to the provided command
exec "$@"
